export function buildRichExplanation(question: ExplainableQuestion): RichExplanation {
  const text = `${question.category} ${question.subcategory ?? ""}`;
  const topic = topicGuides.find((guide) => guide.test.test(text));
  const category = categoryGuides[question.category] ?? defaultGuide;
  const base = topic ?? category;
  const summary = question.learningPoint || question.explanation || "正解の根拠と関連知識を確認しましょう。";

  return {
    summary,
    beginner: base.beginner,
    memorize: base.memorize,
    solveTips: base.solveTips,
    compare: topic?.compare ?? category.compare ?? [],
  };
}
