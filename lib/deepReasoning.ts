function genericReason(question: ReasoningQuestion): Omit<DeepReasoning, "conclusion"> {
  const point = question.learningPoint || question.explanation || "問題の定義・条件に合う選択肢を選びます。";
  const sub = question.subcategory || question.category;
  const isCalc = /計算|CPI|可用性|待ち行列|損益|EVM|クリティカル|アローダイアグラム|組合せ|ビット|正規分布|CPU|ハミング|信頼性|進捗/.test(sub);
  const isLaw = /法|著作権|契約|派遣|署名/.test(sub) || /法務/.test(question.category);
  const isSecurity = /暗号|セキュリティ|XSS|インジェクション|SBOM|PSIRT|CSIRT|認証|VPN|IPsec|フォレンジックス|JPCERT|ハッシュ/.test(sub);

  const steps = isCalc
    ? [
        `この問題の中心論点は「${sub}」です。まず、問題文から与えられた数値・条件と、求める値を分けます。`,
        `次に「${point}」という関係を使います。式や処理順を一気に暗算せず、途中値を1段ずつ書くのが安全です。`,
        "最後に計算結果・条件を選択肢と照合します。正解選択肢は、この関係を正しく適用した結果と一致します。"
      ]
    : isLaw
      ? [
          `この問題は「${sub}」のルールを、主語・行為・条件・法的効果に分けて判定する問題です。`,
          `判断の軸は「${point}」です。選択肢の断定表現（常に、必ず、一律に等）がこのルールより広すぎないかも確認します。`,
          "正解選択肢は、この要件を満たした範囲だけを適切に説明しており、他の選択肢は要件を省略・過度に一般化・別制度と混同しています。"
        ]
      : isSecurity
        ? [
            `この問題では「${sub}」が『何を守る/何を確認する/どこで働く技術か』を特定します。`,
            `正答根拠は「${point}」です。攻撃対象・処理する層・鍵の使い方・主体など、問題文のキーワードと定義を対応させます。`,
            "正解選択肢だけが目的と仕組みの両方に一致します。他の選択肢は別のセキュリティ技術の説明か、処理主体・層・鍵の方向が逆です。"
          ]
        : [
            `この問題は「${sub}」の定義・目的を正しく理解しているかを確認する問題です。`,
            `正答根拠は「${point}」です。まずこの一文を『誰が・何を・何のためにするものか』へ言い換えます。`,
            "その言い換えと完全に一致する選択肢が正解です。他の選択肢は、似た用語の説明、目的が逆、対象が違う、又は一部だけ正しい説明になっています。"
          ];

  return {
    steps,
    eliminate: isCalc
      ? ["数値問題の誤答は、単位変換・式の逆転・条件の読み落としから生じることが多いので、選択肢へ行く前に途中式を作ります。", "値が極端に大きい/小さい選択肢は、概算で先に除外できることがあります。"]
      : ["似た用語を『知っているか』ではなく、問題で問われる目的・対象・主体に一致するかで一つずつ判定します。", "『常に』『必ず』『〜だけ』など強い断定は、定義より範囲が広すぎないか確認します。"],
    takeaway: `「${sub}」は、正解肢の丸暗記ではなく「${point}」を自分の言葉で説明できる状態を目指してください。`
  };
}

export function buildDeepReasoning(question: ReasoningQuestion): DeepReasoning {
  const label = typeof question.answer === "number" ? LABELS[question.answer] ?? "正解選択肢" : "正解選択肢";
  const body = question.id && exact[question.id] ? exact[question.id] : genericReason(question);
  return {
    conclusion: `正解は「${label}」です。`,
    ...body,
  };
}
